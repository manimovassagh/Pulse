//! The build pipeline: TSX source → Rust crate → `cargo` → `.wasm` bundle.

use crate::codegen::{self, CodegenOptions};
use crate::{lower, optimize, parser};
use std::fs;
use std::path::{Path, PathBuf};
use std::process::Command;

/// The browser loader, embedded so the CLI is a single self-contained binary.
pub const LOADER_JS: &str = include_str!("../../../runtime/pulse.js");

/// Compiles TSX source to Rust source. Errors come back already rendered with
/// file, line, column and a caret.
pub fn compile_to_rust(source: &str, file_name: &str) -> Result<String, String> {
    let render = |d: crate::diagnostic::Diagnostic| d.render(file_name, source);
    let program = parser::parse(source).map_err(render)?;
    let mut module = lower::lower(&program).map_err(render)?;
    optimize::optimize(&mut module);
    let opts = CodegenOptions { source_name: file_name.to_string(), ..Default::default() };
    Ok(codegen::generate(&module, &opts))
}

/// Parses and type-checks only.
pub fn check(source: &str, file_name: &str) -> Result<(), String> {
    let program = parser::parse(source).map_err(|d| d.render(file_name, source))?;
    lower::lower(&program).map_err(|d| d.render(file_name, source))?;
    Ok(())
}

pub struct BuildOptions {
    pub entry: PathBuf,
    pub out_dir: PathBuf,
    /// Where the generated crate and its `target/` directory live.
    pub cache_dir: PathBuf,
    /// Path to the `pulse-runtime` crate.
    pub runtime_path: PathBuf,
    /// Optimized (`--release`) WebAssembly.
    pub release: bool,
}

impl BuildOptions {
    /// Defaults: output to `dist/`, cache in `.pulse/`, runtime from
    /// `$PULSE_RUNTIME_PATH` or from this repository.
    pub fn new(entry: PathBuf) -> Self {
        BuildOptions {
            entry,
            out_dir: PathBuf::from("dist"),
            cache_dir: PathBuf::from(".pulse"),
            runtime_path: default_runtime_path(),
            release: true,
        }
    }
}

pub fn default_runtime_path() -> PathBuf {
    std::env::var_os("PULSE_RUNTIME_PATH")
        .map(PathBuf::from)
        .unwrap_or_else(|| Path::new(env!("CARGO_MANIFEST_DIR")).join("../pulse-runtime"))
}

/// Writes the generated application crate into `dir`. Files are only
/// rewritten when their content changes, so cargo can skip rebuilding.
pub fn write_app_crate(dir: &Path, rust_source: &str, runtime_path: &Path) -> Result<(), String> {
    let runtime = fs::canonicalize(runtime_path)
        .map_err(|e| format!("pulse-runtime not found at {}: {e}", runtime_path.display()))?;
    let manifest = format!(
        r#"# @generated by pulse-compiler. Do not edit.
[package]
name = "pulse-app"
version = "0.0.0"
edition = "2021"
publish = false

[lib]
path = "lib.rs"
crate-type = ["cdylib", "rlib"]

[dependencies]
pulse-runtime = {{ path = '{}' }}

[profile.release]
opt-level = "z"
lto = true
codegen-units = 1
panic = "abort"
strip = true

# Not part of any enclosing workspace.
[workspace]
"#,
        runtime.display()
    );
    fs::create_dir_all(dir).map_err(|e| format!("cannot create {}: {e}", dir.display()))?;
    write_if_changed(&dir.join("Cargo.toml"), &manifest)?;
    write_if_changed(&dir.join("lib.rs"), rust_source)
}

fn write_if_changed(path: &Path, content: &str) -> Result<(), String> {
    if fs::read_to_string(path).ok().as_deref() == Some(content) {
        return Ok(());
    }
    fs::write(path, content).map_err(|e| format!("cannot write {}: {e}", path.display()))
}

/// Formats Rust source with `rustfmt` when it is installed; the generated
/// code is valid either way, formatting only helps humans read it.
pub fn format_rust(source: &str) -> String {
    use std::io::Write;
    use std::process::Stdio;
    let child = Command::new("rustfmt")
        .args(["--edition", "2021", "--emit", "stdout"])
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::null())
        .spawn();
    let Ok(mut child) = child else { return source.to_string() };
    if let Some(mut stdin) = child.stdin.take() {
        let _ = stdin.write_all(source.as_bytes());
    }
    match child.wait_with_output() {
        Ok(out) if out.status.success() => String::from_utf8(out.stdout).unwrap_or_else(|_| source.to_string()),
        _ => source.to_string(),
    }
}

/// What a successful build produced.
pub struct BuildReport {
    pub wasm_path: PathBuf,
    pub wasm_bytes: u64,
}

/// Runs the full pipeline and writes `index.html`, `app.wasm` and `pulse.js`
/// to the output directory.
pub fn build(opts: &BuildOptions) -> Result<BuildReport, String> {
    let source = fs::read_to_string(&opts.entry)
        .map_err(|e| format!("cannot read {}: {e}", opts.entry.display()))?;
    if opts.entry.extension().and_then(|e| e.to_str()) != Some("tsx") {
        return Err(format!(
            "{}: Pulse apps are written in TypeScript; the entry file must be a `.tsx` file",
            opts.entry.display()
        ));
    }
    let file_name = opts.entry.file_name().unwrap().to_string_lossy().to_string();
    let rust = format_rust(&compile_to_rust(&source, &file_name)?);

    let crate_dir = opts.cache_dir.join("app");
    write_app_crate(&crate_dir, &rust, &opts.runtime_path)?;

    let target_dir = opts.cache_dir.join("target");
    let mut cmd = Command::new(std::env::var("CARGO").unwrap_or_else(|_| "cargo".into()));
    cmd.args(["build", "--quiet", "--lib", "--target", "wasm32-unknown-unknown", "--manifest-path"])
        .arg(crate_dir.join("Cargo.toml"))
        .arg("--target-dir")
        .arg(&target_dir);
    if opts.release {
        cmd.arg("--release");
    }
    let status = cmd.status().map_err(|e| format!("failed to run cargo: {e}"))?;
    if !status.success() {
        return Err(format!(
            "cargo failed to compile the generated code (see {}).\n\
             hint: make sure the target is installed: rustup target add wasm32-unknown-unknown",
            crate_dir.join("lib.rs").display()
        ));
    }

    let profile = if opts.release { "release" } else { "debug" };
    let built = target_dir.join("wasm32-unknown-unknown").join(profile).join("pulse_app.wasm");
    fs::create_dir_all(&opts.out_dir).map_err(|e| format!("cannot create {}: {e}", opts.out_dir.display()))?;
    let wasm_path = opts.out_dir.join("app.wasm");
    fs::copy(&built, &wasm_path).map_err(|e| format!("cannot copy {}: {e}", built.display()))?;
    fs::write(opts.out_dir.join("pulse.js"), LOADER_JS).map_err(|e| e.to_string())?;
    fs::write(opts.out_dir.join("index.html"), index_html(&opts.entry)?).map_err(|e| e.to_string())?;

    let wasm_bytes = fs::metadata(&wasm_path).map(|m| m.len()).unwrap_or(0);
    Ok(BuildReport { wasm_path, wasm_bytes })
}

/// Uses the app's own `index.html` (next to the entry file or one directory
/// up) or falls back to a minimal page.
fn index_html(entry: &Path) -> Result<String, String> {
    let dir = entry.parent().unwrap_or(Path::new("."));
    for candidate in [dir.join("index.html"), dir.join("../index.html")] {
        if candidate.is_file() {
            return fs::read_to_string(&candidate).map_err(|e| format!("cannot read {}: {e}", candidate.display()));
        }
    }
    Ok(DEFAULT_INDEX_HTML.to_string())
}

pub const DEFAULT_INDEX_HTML: &str = r#"<!doctype html>
<html lang="en">
  <head>
    <meta charset="utf-8" />
    <meta name="viewport" content="width=device-width, initial-scale=1" />
    <title>Pulse app</title>
  </head>
  <body>
    <div id="app"></div>
    <script type="module">
      import { start } from "./pulse.js";
      start("./app.wasm");
    </script>
  </body>
</html>
"#;
