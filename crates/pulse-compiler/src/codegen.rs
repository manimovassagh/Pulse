//! Rust code generation from the optimized IR.
//!
//! Every Pulse module becomes one Rust library crate that links against
//! `pulse-runtime` and exports two functions to the JavaScript loader:
//! `pulse_start` (mount the root component) and `pulse_dispatch` (run an
//! event handler).
//!
//! Naming scheme for the generated code, which keeps user names from
//! clashing with Rust keywords or internals:
//!
//! | TSX                      | Rust                            |
//! |--------------------------|---------------------------------|
//! | local `x`                | `v_x`                           |
//! | module-level `x`         | `g_x()` (thread-local)          |
//! | function `Foo`           | `f_Foo`                         |
//! | internal temporaries     | `__el`, `__t`, `__rhs`, `__f`   |
//!
//! JSX compiles to straight-line DOM construction. Only text and attributes
//! whose expression reads reactive state get an `effect`; everything else is
//! created once.

use crate::ast::{AssignOp, BinOp, UnaryOp};
use crate::ir::*;
use std::collections::BTreeSet;

/// Options for code generation.
pub struct CodegenOptions {
    /// CSS selector of the element the root component is mounted into.
    pub mount_selector: String,
    /// Name of the source file, for the header comment.
    pub source_name: String,
}

impl Default for CodegenOptions {
    fn default() -> Self {
        CodegenOptions { mount_selector: "#app".into(), source_name: "App.tsx".into() }
    }
}

/// Generates the Rust source of the application crate.
pub fn generate(module: &Module, opts: &CodegenOptions) -> String {
    let mut out = String::new();
    out.push_str(&format!(
        "// @generated by pulse-compiler from {}. Do not edit.\n\
         #![allow(unused, non_snake_case, non_upper_case_globals, unused_parens, unused_braces, clippy::all)]\n\n\
         use pulse_runtime::prelude::*;\n\n",
        opts.source_name
    ));

    for g in &module.globals {
        let ty = rust_ty(&g.ty);
        let name = mangle(&g.name);
        out.push_str(&format!(
            "thread_local! {{\n    static G_{name}: {ty} = {};\n}}\n\n\
             fn g_{name}() -> {ty} {{\n    G_{name}.with(|v| v.clone())\n}}\n\n",
            expr(&g.init)
        ));
    }

    for f in &module.functions {
        let params: Vec<String> =
            f.params.iter().map(|(n, t)| format!("{}: {}", local(n), rust_ty(t))).collect();
        let ret = if f.ret == Ty::Void { String::new() } else { format!(" -> {}", rust_ty(&f.ret)) };
        out.push_str(&format!("fn f_{}({}){ret} {{\n", mangle(&f.name), params.join(", ")));
        for s in &f.body {
            out.push_str(&format!("    {}\n", stmt(s)));
        }
        out.push_str("}\n\n");
    }

    out.push_str(&format!(
        "/// Entry point called by the JavaScript loader.\n\
         #[no_mangle]\n\
         pub extern \"C\" fn pulse_start() {{\n    \
             pulse_runtime::dom::install_panic_hook();\n    \
             mount(f_{}(), {:?});\n\
         }}\n\n\
         /// Runs the event handler registered under `handler`.\n\
         #[no_mangle]\n\
         pub extern \"C\" fn pulse_dispatch(handler: u32) {{\n    \
             pulse_runtime::dom::dispatch(handler);\n\
         }}\n",
        mangle(&module.entry),
        opts.mount_selector
    ));
    out
}

// ----- names and types -------------------------------------------------------

/// Makes a TSX identifier a valid Rust identifier fragment.
fn mangle(name: &str) -> String {
    name.replace('$', "_dollar_")
}

fn local(name: &str) -> String {
    format!("v_{}", mangle(name))
}

fn rust_ty(ty: &Ty) -> String {
    match ty {
        Ty::Number => "f64".into(),
        Ty::String => "String".into(),
        Ty::Bool => "bool".into(),
        Ty::Void => "()".into(),
        Ty::Element => "Node".into(),
        Ty::Signal(t) => format!("Signal<{}>", rust_ty(t)),
        Ty::Computed(t) => format!("Computed<{}>", rust_ty(t)),
        Ty::Fn(params, ret) => {
            let params: Vec<String> = params.iter().map(rust_ty).collect();
            let ret = if **ret == Ty::Void { String::new() } else { format!(" -> {}", rust_ty(ret)) };
            format!("Rc<dyn Fn({}){ret}>", params.join(", "))
        }
    }
}

/// Values of these types are `Copy` in Rust and need no `.clone()`.
fn is_copy(ty: &Ty) -> bool {
    matches!(ty, Ty::Number | Ty::Bool | Ty::Void | Ty::Element | Ty::Signal(_) | Ty::Computed(_))
}

fn num_lit(n: f64) -> String {
    if n.is_nan() {
        "f64::NAN".into()
    } else if n.is_infinite() {
        if n > 0.0 { "f64::INFINITY" } else { "f64::NEG_INFINITY" }.into()
    } else if n.is_sign_negative() {
        format!("(-{:?}_f64)", -n)
    } else {
        format!("{n:?}_f64")
    }
}

// ----- statements --------------------------------------------------------------

fn stmt(s: &Stmt) -> String {
    match s {
        Stmt::Let { name, init } => {
            format!("let {}: {} = {};", local(name), rust_ty(&init.ty), expr(init))
        }
        Stmt::Expr(e) => format!("{};", expr(e)),
        Stmt::Return(Some(e)) => format!("return {};", expr(e)),
        Stmt::Return(None) => "return;".into(),
        Stmt::If { cond, then, els } => {
            let mut out = format!("if {} {{ {} }}", expr(cond), block(then));
            if !els.is_empty() {
                out.push_str(&format!(" else {{ {} }}", block(els)));
            }
            out
        }
    }
}

fn block(stmts: &[Stmt]) -> String {
    stmts.iter().map(stmt).collect::<Vec<_>>().join(" ")
}

// ----- expressions ---------------------------------------------------------------

fn expr(e: &Expr) -> String {
    match &e.kind {
        ExprKind::Num(n) => num_lit(*n),
        ExprKind::Str(s) => format!("String::from({s:?})"),
        ExprKind::Bool(b) => b.to_string(),
        ExprKind::Local(n) if is_copy(&e.ty) => local(n),
        ExprKind::Local(n) => format!("{}.clone()", local(n)),
        ExprKind::Global(n) => format!("g_{}()", mangle(n)),
        ExprKind::Read(sig) => format!("{}.get()", expr(sig)),
        ExprKind::Write { signal, op, value } => write(signal, *op, value),
        ExprKind::Unary { op, expr: x } => match op {
            UnaryOp::Not => format!("(!{})", expr(x)),
            UnaryOp::Neg => format!("(-{})", expr(x)),
            UnaryOp::Plus => expr(x),
        },
        ExprKind::Binary { op, left, right } => {
            format!("({} {} {})", expr(left), binop(*op), expr(right))
        }
        ExprKind::Concat(parts) => concat(parts),
        ExprKind::Cond { test, cons, alt } => {
            format!("(if {} {{ {} }} else {{ {} }})", expr(test), expr(cons), expr(alt))
        }
        ExprKind::Call { func, args } => format!("f_{}({})", mangle(func), args_list(args)),
        ExprKind::CallValue { callee, args } => {
            let f = match &callee.kind {
                ExprKind::Local(n) => local(n),
                _ => expr(callee),
            };
            format!("({f})({})", args_list(args))
        }
        ExprKind::Closure { .. } => format!("Rc::new({})", callable(e)),
        ExprKind::Signal(init) => format!("signal({})", expr(init)),
        ExprKind::Computed(f) => format!("computed({})", callable(f)),
        ExprKind::Effect(f) => format!("effect({})", callable(f)),
        ExprKind::Batch(f) => format!("batch({})", callable(f)),
        ExprKind::Untrack(f) => format!("untrack({})", callable(f)),
        ExprKind::Log(args) => {
            let parts: Vec<String> = args.iter().map(to_text).collect();
            format!("console_log(&[{}].join(\" \"))", parts.join(", "))
        }
        ExprKind::Element(n) => node(n),
    }
}

fn args_list(args: &[Expr]) -> String {
    args.iter().map(expr).collect::<Vec<_>>().join(", ")
}

fn binop(op: BinOp) -> &'static str {
    match op {
        BinOp::Add => "+",
        BinOp::Sub => "-",
        BinOp::Mul => "*",
        BinOp::Div => "/",
        BinOp::Rem => "%",
        BinOp::Eq => "==",
        BinOp::Ne => "!=",
        BinOp::Lt => "<",
        BinOp::Le => "<=",
        BinOp::Gt => ">",
        BinOp::Ge => ">=",
        BinOp::And => "&&",
        BinOp::Or => "||",
    }
}

/// Converts a primitive-typed expression to a `String`.
fn to_text(e: &Expr) -> String {
    match (&e.kind, &e.ty) {
        (ExprKind::Str(s), _) => format!("String::from({s:?})"),
        (_, Ty::String) => expr(e),
        _ => format!("ToText::to_text(&{})", expr(e)),
    }
}

fn concat(parts: &[Expr]) -> String {
    match parts {
        [one] => to_text(one),
        _ => format!("[{}].concat()", parts.iter().map(to_text).collect::<Vec<_>>().join(", ")),
    }
}

fn write(signal: &Expr, op: AssignOp, value: &Expr) -> String {
    let sig = expr(signal);
    if op == AssignOp::Assign {
        return format!("{sig}.set({})", expr(value));
    }
    let inner = match &signal.ty {
        Ty::Signal(t) => (**t).clone(),
        other => other.clone(),
    };
    if inner == Ty::String {
        // Only `+=` type-checks for strings.
        return format!(
            "{{ let __rhs = {}; {sig}.update(move |__v| __v.push_str(&__rhs)); }}",
            to_text(value)
        );
    }
    let op = match op {
        AssignOp::Add => "+=",
        AssignOp::Sub => "-=",
        AssignOp::Mul => "*=",
        AssignOp::Div => "/=",
        AssignOp::Assign => unreachable!(),
    };
    // Evaluate the right-hand side before the signal's value is borrowed.
    format!("{{ let __rhs = {}; {sig}.update(move |__v| *__v {op} __rhs); }}", expr(value))
}

// ----- closures -------------------------------------------------------------------

/// Emits a Rust closure (not boxed) for a function-typed expression, suitable
/// for passing to `effect`, `computed`, `on`, ...
fn callable(e: &Expr) -> String {
    match &e.kind {
        ExprKind::Closure { params, body } => {
            let ret = match &e.ty {
                Ty::Fn(_, r) => (**r).clone(),
                _ => Ty::Void,
            };
            let mut bound: Vec<String> = params.iter().map(|p| p.0.clone()).collect();
            let mut captured = BTreeSet::new();
            free_in_stmts(body, &mut bound, &mut captured);
            let params: Vec<String> =
                params.iter().map(|(n, t)| format!("{}: {}", local(n), rust_ty(t))).collect();
            let ret = if ret == Ty::Void { String::new() } else { format!(" -> {}", rust_ty(&ret)) };
            with_captures(&captured, &format!("move |{}|{ret} {{ {} }}", params.join(", "), block(body)))
        }
        _ => {
            // A function-typed value (`Rc<dyn Fn>`): forward to it.
            let Ty::Fn(params, _) = &e.ty else { unreachable!("callable on non-function") };
            let names: Vec<String> = (0..params.len()).map(|i| format!("__a{i}")).collect();
            let typed: Vec<String> =
                names.iter().zip(params).map(|(n, t)| format!("{n}: {}", rust_ty(t))).collect();
            format!(
                "{{ let __f = {}; move |{}| (__f)({}) }}",
                expr(e),
                typed.join(", "),
                names.join(", ")
            )
        }
    }
}

/// An event handler: a closure returning `()`.
fn handler(e: &Expr) -> String {
    let returns_unit = matches!(&e.ty, Ty::Fn(_, r) if **r == Ty::Void);
    if returns_unit {
        callable(e)
    } else {
        format!("{{ let __h = {}; move || {{ __h(); }} }}", callable(e))
    }
}

/// Wraps `code` (a `move` closure) so it captures its own clones of the
/// given locals, leaving the originals usable afterwards.
fn with_captures(captured: &BTreeSet<String>, code: &str) -> String {
    if captured.is_empty() {
        return code.to_string();
    }
    let clones: Vec<String> =
        captured.iter().map(|n| format!("let {0} = {0}.clone();", local(n))).collect();
    format!("{{ {} {code} }}", clones.join(" "))
}

/// Collects locals that `stmts` reads but does not declare.
fn free_in_stmts(stmts: &[Stmt], bound: &mut Vec<String>, out: &mut BTreeSet<String>) {
    let mark = bound.len();
    for s in stmts {
        match s {
            Stmt::Let { name, init } => {
                free_in_expr(init, bound, out);
                bound.push(name.clone());
            }
            Stmt::Expr(e) | Stmt::Return(Some(e)) => free_in_expr(e, bound, out),
            Stmt::Return(None) => {}
            Stmt::If { cond, then, els } => {
                free_in_expr(cond, bound, out);
                free_in_stmts(then, bound, out);
                free_in_stmts(els, bound, out);
            }
        }
    }
    bound.truncate(mark);
}

fn free_in_expr(e: &Expr, bound: &mut Vec<String>, out: &mut BTreeSet<String>) {
    match &e.kind {
        ExprKind::Local(n) => {
            if !bound.contains(n) {
                out.insert(n.clone());
            }
        }
        ExprKind::Num(_) | ExprKind::Str(_) | ExprKind::Bool(_) | ExprKind::Global(_) => {}
        ExprKind::Read(x)
        | ExprKind::Unary { expr: x, .. }
        | ExprKind::Signal(x)
        | ExprKind::Computed(x)
        | ExprKind::Effect(x)
        | ExprKind::Batch(x)
        | ExprKind::Untrack(x) => free_in_expr(x, bound, out),
        ExprKind::Write { signal, value, .. } => {
            free_in_expr(signal, bound, out);
            free_in_expr(value, bound, out);
        }
        ExprKind::Binary { left, right, .. } => {
            free_in_expr(left, bound, out);
            free_in_expr(right, bound, out);
        }
        ExprKind::Cond { test, cons, alt } => {
            free_in_expr(test, bound, out);
            free_in_expr(cons, bound, out);
            free_in_expr(alt, bound, out);
        }
        ExprKind::Concat(xs) | ExprKind::Log(xs) | ExprKind::Call { args: xs, .. } => {
            xs.iter().for_each(|x| free_in_expr(x, bound, out))
        }
        ExprKind::CallValue { callee, args } => {
            free_in_expr(callee, bound, out);
            args.iter().for_each(|x| free_in_expr(x, bound, out));
        }
        ExprKind::Closure { params, body } => {
            let mark = bound.len();
            bound.extend(params.iter().map(|p| p.0.clone()));
            free_in_stmts(body, bound, out);
            bound.truncate(mark);
        }
        ExprKind::Element(n) => free_in_node(n, bound, out),
    }
}

fn free_in_node(n: &Node, bound: &mut Vec<String>, out: &mut BTreeSet<String>) {
    match n {
        Node::Element { attrs, events, children, .. } => {
            attrs.iter().for_each(|a| free_in_expr(&a.value, bound, out));
            events.iter().for_each(|ev| free_in_expr(&ev.handler, bound, out));
            children.iter().for_each(|c| free_in_node(c, bound, out));
        }
        Node::Text(e) | Node::Embed(e) => free_in_expr(e, bound, out),
        Node::Component(_) => {}
    }
}

fn free_locals(e: &Expr) -> BTreeSet<String> {
    let mut out = BTreeSet::new();
    free_in_expr(e, &mut Vec::new(), &mut out);
    out
}

// ----- DOM nodes --------------------------------------------------------------------

/// Emits a block expression that builds `n` and evaluates to its `Node`.
fn node(n: &Node) -> String {
    match n {
        Node::Element { tag, attrs, events, children } => {
            let mut out = format!("{{ let __el = create_element({tag:?});");
            for a in attrs {
                out.push(' ');
                out.push_str(&attr(a));
            }
            for ev in events {
                out.push_str(&format!(" on(__el, {:?}, {});", ev.name, handler(&ev.handler)));
            }
            for c in children {
                out.push_str(&format!(" append_child(__el, {});", node(c)));
            }
            out.push_str(" __el }");
            out
        }
        Node::Text(e) => match &e.kind {
            ExprKind::Str(s) => format!("create_text({s:?})"),
            _ if e.is_reactive() => {
                let update = format!("move || set_text(__t, &{})", expr(e));
                format!(
                    "{{ let __t = create_text(\"\"); effect({}); __t }}",
                    with_captures(&free_locals(e), &update)
                )
            }
            _ => format!("create_text(&{})", expr(e)),
        },
        Node::Component(name) => format!("f_{}()", mangle(name)),
        Node::Embed(e) => expr(e),
    }
}

fn attr(a: &Attr) -> String {
    let set = |value: &str| match a.value.ty {
        Ty::Bool => format!("set_bool_attribute(__el, {:?}, {value})", a.name),
        _ => format!("set_attribute(__el, {:?}, &{value})", a.name),
    };
    match &a.value.kind {
        ExprKind::Str(s) => format!("set_attribute(__el, {:?}, {s:?});", a.name),
        _ if a.value.is_reactive() => {
            let update = format!("move || {}", set(&expr(&a.value)));
            format!("effect({});", with_captures(&free_locals(&a.value), &update))
        }
        _ => format!("{};", set(&expr(&a.value))),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn gen(src: &str) -> String {
        let mut m = crate::lower::lower(&crate::parser::parse(src).unwrap()).unwrap();
        crate::optimize::optimize(&mut m);
        generate(&m, &CodegenOptions::default())
    }

    #[test]
    fn counter_codegen() {
        let out = gen(r#"
            const count = signal<number>(0);
            export default function App(): JSX.Element {
              return <button class="btn" onClick={() => count.value++}>Count: {count.value}</button>;
            }
        "#);
        assert!(out.contains("static G_count: Signal<f64> = signal(0.0_f64);"), "{out}");
        assert!(out.contains(r#"set_attribute(__el, "class", "btn");"#), "{out}");
        assert!(out.contains("g_count().update(move |__v| *__v += __rhs)"), "{out}");
        assert!(
            out.contains(r#"effect(move || set_text(__t, &[String::from("Count: "), ToText::to_text(&g_count().get())].concat()))"#),
            "{out}"
        );
        assert!(out.contains(r##"mount(f_App(), "#app")"##), "{out}");
    }

    #[test]
    fn static_content_has_no_effects() {
        let out = gen(r#"
            const title = "Hi";
            export default function App(): JSX.Element { return <h1 id={"x" + 1}>{title}</h1>; }
        "#);
        let app = &out[out.find("fn f_App").unwrap()..];
        let app = &app[..app.find("pulse_start").unwrap()];
        assert!(!app.contains("effect("), "{app}");
        assert!(app.contains(r#"set_attribute(__el, "id", "x1");"#), "{app}");
        assert!(app.contains("create_text(&g_title())"), "{app}");
    }

    #[test]
    fn closures_clone_captured_locals() {
        let out = gen(r#"
            export default function App(): JSX.Element {
              const name = "Pulse";
              const n = signal(0);
              effect(() => console.log(name, n.value));
              return <div></div>;
            }
        "#);
        assert!(
            out.contains("effect({ let v_n = v_n.clone(); let v_name = v_name.clone(); move || { console_log("),
            "{out}"
        );
    }

    #[test]
    fn number_literals() {
        assert_eq!(num_lit(1.0), "1.0_f64");
        assert_eq!(num_lit(-2.5), "(-2.5_f64)");
        assert_eq!(num_lit(1e21), "1e21_f64");
        assert_eq!(num_lit(f64::NAN), "f64::NAN");
    }
}
