//! Compiling generated Rust to WebAssembly with cargo.
//!
//! The generated code lives in a tiny crate inside the cache directory. Files
//! are only rewritten when their content changes and the target directory is
//! kept between builds, so cargo's incremental compilation applies: the
//! runtime is compiled once and a typical rebuild takes a fraction of a
//! second.

use std::fs;
use std::io::Write;
use std::path::{Path, PathBuf};
use std::process::{Command, Stdio};

const TARGET: &str = "wasm32-unknown-unknown";

/// Writes the generated application crate into `dir`.
pub fn write_app_crate(dir: &Path, rust_source: &str, runtime_path: &Path) -> Result<(), String> {
    let runtime = fs::canonicalize(runtime_path)
        .map_err(|e| format!("pulse-runtime not found at {}: {e}", runtime_path.display()))?;
    let manifest = format!(
        r#"# @generated by pulse-build. Do not edit.
[package]
name = "pulse-app"
version = "0.0.0"
edition = "2021"
publish = false

[lib]
path = "lib.rs"
crate-type = ["cdylib", "rlib"]

[dependencies]
pulse-runtime = {{ path = '{}' }}

[profile.release]
opt-level = "z"
lto = true
codegen-units = 1
panic = "abort"
strip = true

# Not part of any enclosing workspace.
[workspace]
"#,
        runtime.display()
    );
    fs::create_dir_all(dir).map_err(|e| format!("cannot create {}: {e}", dir.display()))?;
    write_if_changed(&dir.join("Cargo.toml"), &manifest)?;
    write_if_changed(&dir.join("lib.rs"), rust_source)
}

/// Builds the crate in `crate_dir` for the browser and returns the path of
/// the produced `.wasm` file.
pub fn build_wasm(crate_dir: &Path, target_dir: &Path, release: bool) -> Result<PathBuf, String> {
    let mut cmd = Command::new(std::env::var("CARGO").unwrap_or_else(|_| "cargo".into()));
    cmd.args(["build", "--quiet", "--lib", "--target", TARGET, "--manifest-path"])
        .arg(crate_dir.join("Cargo.toml"))
        .arg("--target-dir")
        .arg(target_dir);
    if release {
        cmd.arg("--release");
    }
    let output = cmd.output().map_err(|e| format!("failed to run cargo: {e}"))?;
    if !output.status.success() {
        return Err(format!(
            "{}\ncargo failed to compile the generated code (see {}).\n\
             hint: make sure the target is installed: rustup target add {TARGET}",
            String::from_utf8_lossy(&output.stderr).trim_end(),
            crate_dir.join("lib.rs").display()
        ));
    }
    let profile = if release { "release" } else { "debug" };
    Ok(target_dir.join(TARGET).join(profile).join("pulse_app.wasm"))
}

/// Formats Rust source with `rustfmt` when it is installed; the generated
/// code is valid either way, formatting only helps humans read it.
pub fn format_rust(source: &str) -> String {
    let child = Command::new("rustfmt")
        .args(["--edition", "2021", "--emit", "stdout"])
        .stdin(Stdio::piped())
        .stdout(Stdio::piped())
        .stderr(Stdio::null())
        .spawn();
    let Ok(mut child) = child else { return source.to_string() };
    if let Some(mut stdin) = child.stdin.take() {
        let _ = stdin.write_all(source.as_bytes());
    }
    match child.wait_with_output() {
        Ok(out) if out.status.success() => String::from_utf8(out.stdout).unwrap_or_else(|_| source.to_string()),
        _ => source.to_string(),
    }
}

fn write_if_changed(path: &Path, content: &str) -> Result<(), String> {
    if fs::read_to_string(path).ok().as_deref() == Some(content) {
        return Ok(());
    }
    fs::write(path, content).map_err(|e| format!("cannot write {}: {e}", path.display()))
}
